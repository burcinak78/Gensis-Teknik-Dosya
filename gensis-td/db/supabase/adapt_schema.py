"""Adapt a Supabase `pg_dump --schema-only --schema=public` file to the self-hosted Postgres schema.

Removes what only makes sense inside Supabase (RLS policies, auth.uid() helpers, pg_dump session
settings) and points auth.users references at public.users. Authorization moves to the backend.

Usage: python3 -I adapt_schema.py <dump.sql> <out.sql>
"""
import re
import sys

# Helpers built on auth.uid(); their checks are reimplemented in the backend.
DROPPED_FUNCTIONS = {"current_company_id", "handle_new_user", "is_admin", "is_company_member", "is_staff"}

# Column type fixes applied inside CREATE TABLE: (table, old column definition, new one).
# ilgili_idareler.province_id is integer but references provinces.id (smallint); EF Core needs equal types.
COLUMN_FIXES = [
    ("ilgili_idareler", "province_id integer", "province_id smallint"),
]

DROP_PATTERNS = [
    re.compile(r"^\\(un)?restrict "),
    re.compile(r"^SET "),
    re.compile(r"^SELECT pg_catalog\.set_config"),
    re.compile(r"^CREATE SCHEMA public;"),
    re.compile(r"^COMMENT ON SCHEMA public "),
    re.compile(r"^CREATE POLICY "),
    re.compile(r"^ALTER TABLE \S+ ENABLE ROW LEVEL SECURITY;"),
]


def statements(text):
    """Split into statements, keeping $$-quoted function bodies intact. Comment-only chunks are skipped."""
    buf, in_body = [], False
    for line in text.splitlines():
        if not buf and (not line.strip() or line.startswith("--")):
            continue
        if not buf and line.startswith("\\"):  # psql meta-command: one line, no semicolon
            yield line
            continue
        buf.append(line)
        if line.count("$$") % 2:
            in_body = not in_body
        if not in_body and line.rstrip().endswith(";"):
            yield "\n".join(buf)
            buf = []
    if buf:
        raise SystemExit("unterminated statement:\n" + "\n".join(buf)[:500])


def keep(stmt):
    if any(p.match(stmt) for p in DROP_PATTERNS):
        return False
    m = re.match(r"^(CREATE FUNCTION|COMMENT ON FUNCTION) public\.(\w+)\(", stmt)
    return not (m and m.group(2) in DROPPED_FUNCTIONS)


def fix_columns(stmt, applied):
    for table, old, new in COLUMN_FIXES:
        if stmt.startswith(f"CREATE TABLE public.{table} (") and f"    {old}" in stmt:
            stmt = stmt.replace(f"    {old}", f"    {new}", 1)
            applied.add(table)
    return stmt


def main(src, dst):
    out, applied = [], set()
    for stmt in statements(open(src, encoding="utf-8").read()):
        if keep(stmt):
            stmt = fix_columns(stmt, applied)
            stmt = stmt.replace("REFERENCES auth.users(id)", "REFERENCES public.users(id)")
            # The backend sets owner columns from the session.
            stmt = stmt.replace(" DEFAULT auth.uid()", "")
            out.append(stmt)
    # Functions are created before the tables they read, as in pg_dump.
    missing = {t for t, _, _ in COLUMN_FIXES} - applied
    if missing:
        raise SystemExit(f"column fixes not applied (schema changed?): {sorted(missing)}")
    sql = "SET check_function_bodies = false;\n\n" + "\n\n".join(out) + "\n\nRESET check_function_bodies;\n"
    leftovers = sorted(set(re.findall(r"\b(?:auth|storage|extensions)\.\w+", sql)))
    if leftovers:
        raise SystemExit(f"Supabase references left: {leftovers}")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("-- Generated by db/supabase/adapt_schema.py from a Supabase schema dump. Do not edit by hand.\n\n" + sql)
    print(f"{len(out)} statements → {dst}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
